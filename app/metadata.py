# Resolve a known shortname or modified base title, otherwise clean the supplied identifier.
def get_title(shortname):
    stem = shortname.lower()
    if stem in NAMES:
        return NAMES[stem]
    # Keep a meaningful base title on modified NeoRAGEx archives; show full ID separately.
    base = stem.split("-")[0]
    if base in NAMES:
        return NAMES[base] + " · Mod"
    return shortname.replace("_", " ").replace(".", " ").strip()


# Classify known shortnames and fighting-game prefixes, falling back to the generic category.
def get_category(shortname):
    stem = shortname.lower().split("-")[0]
    if stem.startswith(("kof", "kf10", "kog", "cthd", "lans")) or stem in FIGHTING:
        return "fighting"
    if stem in ACTION:
        return "action"
    if stem in SHOOTER:
        return "shooter"
    if stem in SPORTS:
        return "sports"
    if stem in PUZZLE:
        return "puzzle"
    return "other"
